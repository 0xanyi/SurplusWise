import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // 18px is the surface step of the radius scale; tiles inside a card use
      // 16px and the hero slabs 20px. Flat at rest — elevation is carried by
      // the hairline, not a shadow. A responsive custom property lets child
      // padding overrides apply at every breakpoint instead of losing to sm:p-6.
      "rounded-[18px] border border-border/70 bg-card text-card-foreground [--card-padding:1.25rem] sm:[--card-padding:1.5rem]",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

const CardHeader = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn("flex flex-col space-y-1.5 p-[var(--card-padding)]", className)}
    {...props}
  />
))
CardHeader.displayName = "CardHeader"

const CardTitle = React.forwardRef<
  HTMLHeadingElement,
  React.HTMLAttributes<HTMLHeadingElement> & { as?: "h2" | "h3" }
>(({ className, as: Comp = "h3", ...props }, ref) => (
  <Comp
    ref={ref}
    className={cn(
      "font-display text-base font-semibold leading-none tracking-[-0.015em]",
      className
    )}
    {...props}
  />
))
CardTitle.displayName = "CardTitle"

